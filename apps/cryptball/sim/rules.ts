export function aimHeading(x: number, y: number) {
  if (!x && !y) return 0;
  let best = 0,
    score = -Infinity;
  // The authored headings are the aiming metric. Stable lower-heading ties are
  // part of the rules; no trigonometric reconstruction occurs in simulation.
  for (let i = 0; i < DIRECTIONS.length; i++) {
    const d = DIRECTIONS[i],
      dot = x * d.x + y * d.y;
    const candidate = dot;
    if (candidate > score) {
      best = i;
      score = candidate;
    }
  }
  return best;
}
/** Integer root on quantized 1/65536 units. Basic operations have specified IEEE
 * semantics; unlike hypot/sqrt no implementation approximation enters contacts. */
const ROOT_SEEDS = [
  1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 1024, 2048, 4096, 8192, 16384, 32768,
  65536, 131072, 262144, 524288, 1048576, 2097152, 4194304, 8388608, 16777216,
  33554432, 67108864, 134217728,
] as const;
export function integerSqrt(n: number) {
  if (!Number.isSafeInteger(n) || n < 0)
    throw Error("Invalid square-root domain");
  if (n < 2) return n;
  // Binary search only the literal exponent seeds, then integer Newton converges
  // in at most six refinements. All products at the result fit the exact domain.
  let low = 0,
    high = ROOT_SEEDS.length - 1;
  while (low < high) {
    const mid = Math.floor((low + high) / 2);
    if (ROOT_SEEDS[mid] * ROOT_SEEDS[mid] < n) low = mid + 1;
    else high = mid;
  }
  let root: number = ROOT_SEEDS[low];
  for (;;) {
    const next = Math.floor((root + Math.floor(n / root)) / 2);
    if (next >= root) break;
    root = next;
  }
  while (root * root > n) root--;
  while ((root + 1) * (root + 1) <= n) root++;
  return root;
}
export function length(x: number, y: number) {
  // Inputs may be fractional movement commands; quantize before taking the root.
  const ax = Math.round(x * 256),
    ay = Math.round(y * 256);
  const squared = ax * ax + ay * ay;
  if (Number.isSafeInteger(squared)) return integerSqrt(squared) / 256;
  // World-speed inputs fit exactly in BigInt after their fixed-point conversion.
  const n = BigInt(ax) * BigInt(ax) + BigInt(ay) * BigInt(ay);
  let lo = 0n,
    hi = n + 1n;
  while (hi - lo > 1n) {
    const m = (lo + hi) / 2n;
    if (m * m <= n) lo = m;
    else hi = m;
  }
  return Number(lo) / 256;
}
export function normalized(x: number, y: number) {
  const n = length(x, y);
  return n ? { x: x / n, y: y / n } : { x: 0, y: 0 };
}
