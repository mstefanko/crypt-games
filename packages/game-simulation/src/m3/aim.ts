/** Highest dot product wins; equal dots choose the lowest table index.
 * Differences bounded to 2^24 guarantee each dot sum is below 2^42. */
export function quantizeArenaAim(dx: number, dy: number): number {
  integer(dx, -16777216, 16777216);
  integer(dy, -16777216, 16777216);
  let best = 0,
    score = -Number.MAX_SAFE_INTEGER;
  for (let i = 0; i < 256; i++) {
    const d = AIM_DIRECTIONS[i],
      dot = dx * d[0] + dy * d[1];
    if (dot > score) {
      best = i;
      score = dot;
    }
  }
  return best;
}

export function arenaAimVelocity(
  aim: number,
  speed: number,
): readonly [number, number] {
  integer(aim, 0, 255);
  integer(speed, 0, 32768);
  const d = AIM_DIRECTIONS[aim];
  let x = Math.trunc((d[0] * speed) / AIM_SCALE) || 0;
  let y = Math.trunc((d[1] * speed) / AIM_SCALE) || 0;
  // Nearest-rounded table components can exceed unit length by <1 unit.
  // Conservatively quantize the larger component inward if needed, so the
  // configured speed is a strict Euclidean displacement ceiling.
  if (x * x + y * y > speed * speed) {
    if (Math.abs(x) >= Math.abs(y)) x -= Math.sign(x);
    else y -= Math.sign(y);
  }
  return [x || 0, y || 0];
}
